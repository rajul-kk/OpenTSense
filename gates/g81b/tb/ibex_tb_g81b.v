`timescale 1ns/1ps
// G81b testbench: G72's ibex testbench (opentsense/power/tb/ibex_tb.v) with
//   - memory enlarged to 256 KB (word index addr[17:2]);
//   - data_rdata holding its last value on writes (G81x hold testbench; no X injection);
//   - memory-mapped testbench registers in the top 256 bytes (0x3FF00-0x3FFFF), excluded from the program image:
//       0x3FF00 result (verify_benchmark: 0 = correct)   0x3FF04 done flag (write 1)
//       0x3FF08 timer: raise irq_timer_i this many cycles from now   0x3FF0C clear irq_timer_i
//       0x3FF10 start marker   0x3FF14 stop marker   0x3FF18 phase marker (value printed)
//   - power windows and the activity timeline controlled from the C++ harness (main.cpp) through public signals;
//   - per-region toggle counters (gates/g81b/regions.vh, generated by regions.py from the netlist and G72's placement).
// Plusargs: +hex=<file> +max=<cycles>
module tb(output [31:0] cyc_o);      // cyc_o: the cycle count, read by the harness
  reg clk = 0, rst_n = 0;
  always #0.45 clk = ~clk;                    // 900 ps clock (ASAP7 SDC)
  reg [31:0] mem [0:65535];
  wire instr_req, data_req, data_we; wire [31:0] instr_addr, data_addr, data_wdata; wire [3:0] data_be;
  reg instr_gnt, instr_rvalid, data_gnt, data_rvalid; reg [31:0] instr_rdata, data_rdata;
  reg irq_timer = 0; wire core_sleep;
  ibex_core dut (
    .clk_i(clk), .rst_ni(rst_n), .test_en_i(1'b0), .hart_id_i(32'd0), .boot_addr_i(32'd0),
    .instr_req_o(instr_req), .instr_gnt_i(instr_gnt), .instr_rvalid_i(instr_rvalid), .instr_addr_o(instr_addr), .instr_rdata_i(instr_rdata), .instr_err_i(1'b0),
    .data_req_o(data_req), .data_gnt_i(data_gnt), .data_rvalid_i(data_rvalid), .data_we_o(data_we), .data_be_o(data_be),
    .data_addr_o(data_addr), .data_wdata_o(data_wdata), .data_rdata_i(data_rdata), .data_err_i(1'b0),
    .irq_software_i(1'b0), .irq_timer_i(irq_timer), .irq_external_i(1'b0), .irq_fast_i(15'd0), .irq_nm_i(1'b0),
    .debug_req_i(1'b0), .fetch_enable_i(1'b1), .alert_minor_o(), .alert_major_o(), .core_sleep_o(core_sleep));
  always @(*) begin instr_gnt = instr_req; data_gnt = data_req; end
  integer i; reg [31:0] w;
  reg done = 0; reg [31:0] result = 32'hffffffff; integer cyc = 0, mx = 0, done_cyc = -1, irq_at = -1;
  integer start_cyc = -1, stop_cyc = -1; reg [1023:0] hex;
  assign cyc_o = cyc;
  wire mmio = data_addr[17:8] == 10'h3ff;
  always @(posedge clk) begin
    instr_rvalid <= instr_req; data_rvalid <= data_req;
    // timer: raise first, so a clear (0x3FF0C) in the same cycle wins (its nonblocking assignment comes later)
    if (irq_at >= 0 && cyc >= irq_at) irq_timer <= 1;
    if (instr_req) instr_rdata <= mem[instr_addr[17:2]];
    if (data_req) begin
      if (data_we) begin
        w = mem[data_addr[17:2]];
        if (data_be[0]) w[7:0] = data_wdata[7:0];   if (data_be[1]) w[15:8] = data_wdata[15:8];
        if (data_be[2]) w[23:16] = data_wdata[23:16]; if (data_be[3]) w[31:24] = data_wdata[31:24];
        if (!mmio) mem[data_addr[17:2]] <= w;
        if (mmio) case (data_addr[7:0])
          8'h00: result <= data_wdata;
          8'h04: if (data_wdata == 1) done <= 1;
          8'h08: irq_at <= cyc + data_wdata;
          8'h0c: begin irq_timer <= 0; irq_at <= -1; end
          8'h10: begin start_cyc <= cyc; $display("MARK start cycle=%0d", cyc); end
          8'h14: begin stop_cyc <= cyc; $display("MARK stop cycle=%0d", cyc); end
          8'h18: $display("MARK phase=%0d cycle=%0d", data_wdata, cyc);
          default: ;
        endcase
      end else data_rdata <= mem[data_addr[17:2]];
    end
  end
`include "regions.vh"
  always @(posedge clk) begin
    cyc <= cyc + 1;
    if (done && done_cyc < 0) done_cyc = cyc;
    if ((done && cyc > done_cyc + 5) || cyc >= mx) begin
      $display("RESULT result=%08x done=%0d done_cycle=%0d start=%0d stop=%0d cycles=%0d", result, done, done_cyc, start_cyc, stop_cyc, cyc);
      $finish;
    end
  end
  initial begin
    for (i = 0; i < 65536; i = i + 1) mem[i] = 32'h0000006f;   // jal x0,0 everywhere else
    if (!$value$plusargs("hex=%s", hex)) hex = "prog.hex";
    if (!$value$plusargs("max=%d", mx)) mx = 4000000;
    $readmemh(hex, mem);
    instr_rvalid = 0; data_rvalid = 0; instr_rdata = 0; data_rdata = 0;
    repeat (5) @(posedge clk); rst_n = 1;
  end
endmodule
