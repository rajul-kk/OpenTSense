"""G81b: generate regions.vh, per-region toggle counters for the activity timeline.

The routed ibex netlist is flat (Yosys names such as `_16865_`; no module hierarchy survives), so the timeline groups
nets by placement instead of by module: each net driven by a leaf cell's output pin belongs to the region of the
4 x 4 placement grid (G72's die box and instance locations) holding that cell. Nets driven by the two hierarchical
adder blocks and nets with no placed driver are not counted; their number is printed.
Counting: at every falling clock edge (mid-cycle; zero-delay simulation, values settled), the number of counted nets
whose value differs from the previous falling edge, summed per region over each 1,000-cycle interval and written to
timeline.csv as `cycle,r0,...,r15` (row i = y index from the die's lower edge, as maps.tile_map). The first sample
after reset only primes the previous values. The final row holds the last, partial interval and carries the negative
of its end cycle.
Usage: regions.py <netlist.v> <models dir> <ibex_loc.csv> <out regions.vh> [grid]
"""
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from opentsense.power import maps  # noqa: E402

INTERVAL = 1000


def outputs(models_dir):
    """{cell: set of output pins} from the Icarus/Verilator cell models."""
    out = {}
    for f in glob.glob(os.path.join(models_dir, "*.v")):
        for m in re.finditer(r"\bmodule\s+(\w+)\s*\((.*?)endmodule", open(f).read(), re.S):
            pins = set()
            for d in re.findall(r"^\s*output\s+([^;]*);", m.group(2), re.M):
                pins |= {p.strip() for p in re.sub(r"\[[^\]]*\]", "", d).replace("reg", "").split(",") if p.strip()}
            out[m.group(1)] = pins
    return out


def top_module(netlist):
    t = open(netlist).read()
    m = re.search(r"\bmodule\s+ibex_core\b(.*?)\bendmodule", t, re.S)
    return m.group(1)


def ref(net):
    """Hierarchical reference from tb to a dut net or bit."""
    net = net.strip()
    if net.startswith("\\"):
        name, _, rest = net.partition(" ")
        return f"dut.{name} {rest.strip()}" if rest.strip() else f"dut.{name} "
    return "dut." + net


def main(netlist, models_dir, loc, dst, grid=4):
    cells = outputs(models_dir)
    box, pos = maps.read_locations(loc)
    x0, y0, x1, y1 = box
    body = top_module(netlist)
    groups = collections.defaultdict(list)
    seen, skipped_hier, skipped_unplaced = set(), 0, 0
    for m in re.finditer(r"^\s*(\\\S+|\w+)\s+(\\\S+|\w+)\s*\((.*?)\);", body, re.S | re.M):
        cell, inst, conns = m.group(1), m.group(2), m.group(3)
        if cell in ("input", "output", "wire", "inout", "assign"):
            continue
        if cell not in cells:
            skipped_hier += 1
            continue
        key = inst.lstrip("\\").strip()
        if key not in pos:                    # OpenSTA writes an escaped name's backslashes doubled and brackets escaped
            key = key.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
        if key not in pos:
            skipped_unplaced += 1
            if skipped_unplaced < 4:
                print("unplaced", repr(cell), repr(inst))
            continue
        x, y = pos[key]
        ix = min(grid - 1, int((x - x0) / (x1 - x0) * grid)); iy = min(grid - 1, int((y - y0) / (y1 - y0) * grid))
        for pin, net in re.findall(r"\.(\w+)\s*\(\s*((?:\\\S+\s)|[^()\s]+(?:\s*\[\d+\])?)\s*\)", conns):
            if pin in cells[cell] and net.strip() and net.strip() not in seen and not net.strip().startswith("{"):
                seen.add(net.strip())
                groups[iy * grid + ix].append(net)
    n = grid * grid
    L = [f"// generated by gates/g81b/regions.py: {len(seen)} nets in a {grid} x {grid} placement grid; "
         f"{skipped_hier} hierarchical blocks and {skipped_unplaced} unplaced cells not counted",
         "integer tl_fd; initial tl_fd = $fopen(\"timeline.csv\", \"w\");"]
    for r in range(n):
        nets = groups.get(r, [])
        if not nets:
            L.append(f"wire [0:0] rg{r} = 1'b0;")
        else:
            L.append(f"wire [{len(nets) - 1}:0] rg{r} = {{" + ", ".join(ref(x) for x in nets) + "};")
        L.append(f"reg [{max(len(nets), 1) - 1}:0] rp{r} = 0; integer tg{r} = 0;")
    # tl_primed: the first sample after reset only loads rp (no previous value, so no toggles are counted for it)
    L.append("reg tl_primed = 0;")
    inc = lambda r: f"(tl_primed ? $countones(rg{r} ^ rp{r}) : 0)"  # noqa: E731
    L.append("always @(negedge clk) if (rst_n) begin")
    L.append("  tl_primed <= 1;")
    L.append(f"  if (cyc > 0 && cyc % {INTERVAL} == 0) begin")
    L.append("    $fwrite(tl_fd, \"%0d" + ",%0d" * n + "\\n\", cyc, " + ", ".join(f"tg{r}" for r in range(n)) + ");")
    for r in range(n):
        L.append(f"    tg{r} <= {inc(r)};")
    L.append("  end else begin")
    for r in range(n):
        L.append(f"    tg{r} <= tg{r} + {inc(r)};")
    L.append("  end")
    for r in range(n):
        L.append(f"  rp{r} <= rg{r};")
    L.append("end")
    # the last, partial interval: written with a negative cycle (-cyc) so a reader cannot take it for a full interval
    L.append("final begin $fwrite(tl_fd, \"%0d" + ",%0d" * n + "\\n\", -cyc, " + ", ".join(f"tg{r}" for r in range(n))
             + "); $fclose(tl_fd); end")
    open(dst, "w", newline="\n").write("\n".join(L) + "\n")
    print(f"{len(seen)} nets counted in {n} regions (sizes {[len(groups.get(r, [])) for r in range(n)]}); "
          f"{skipped_hier} hierarchical blocks, {skipped_unplaced} unplaced cells skipped")


if __name__ == "__main__":
    a = sys.argv[1:]
    main(*a[:4], *([int(a[4])] if len(a) > 4 else []))
